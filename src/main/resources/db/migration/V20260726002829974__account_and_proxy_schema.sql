-- Create schema for Proxies and Telegram Accounts

CREATE TABLE proxies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host VARCHAR(255) NOT NULL,
    port INT NOT NULL,
    username VARCHAR(255),
    password VARCHAR(255),
    protocol VARCHAR(50) NOT NULL, -- SOCKS5, HTTP
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE tg_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number VARCHAR(50) NOT NULL UNIQUE,
    username VARCHAR(255),
    status VARCHAR(50) NOT NULL, -- ACTIVE, TEMPORARY_SPAM_BLOCK, PERMANENT_BAN, RE_AUTHORIZATION_REQUIRED
    session_data TEXT,
    proxy_id BIGINT,
    daily_limit INT NOT NULL DEFAULT 15,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_tg_accounts_proxy FOREIGN KEY (proxy_id) REFERENCES proxies(id) ON DELETE SET NULL
);
